class CooperativeRewardShaper:
    """
    Shapes agent rewards in GMN-Football-3 to encourage multi-agent passing
    and penalize unassisted direct shooting / excessive dribbling.
    """

    def __init__(
        self,
        reward_pass_completion: float = 0.30,
        reward_assisted_goal_bonus: float = 0.50,
        penalty_solitary_shot: float = -0.30,
        penalty_ball_hogging: float = -0.02,
        penalty_turnover: float = -0.10,
        max_unassisted_hold_ticks: int = 15,
    ):
        self.r_pass = reward_pass_completion
        self.r_assisted_goal = reward_assisted_goal_bonus
        self.p_solitary_shot = penalty_solitary_shot
        self.p_ball_hogging = penalty_ball_hogging
        self.p_turnover = penalty_turnover
        self.max_hold_ticks = max_unassisted_hold_ticks
        self.total_pass_completed_count: int = 0
        self.total_goal_scored_count: int = 0
        self.total_turnover_conceded_count: int = 0
        self.reset()

    def reset(self) -> None:
        """Reset sequence trackers at the start of an episode."""
        self.pass_chain_length: int = 0
        self.current_holder_id: Optional[str] = None
        self.holder_ticks: int = 0
        self.pass_completed_count: int = 0
        self.goal_scored_count: int = 0
        self.turnover_conceded_count: int = 0
        self.pass_intercepted_count: int = 0
        self.solitary_shot_count: int = 0
        self.assisted_goal_count: int = 0
        self.ball_hogging_count: int = 0

    def get_diagnostics(self) -> Dict[str, Any]:
        """Return episode-level cooperative shaping diagnostics."""
        return {
            "pass_chain_length": self.pass_chain_length,
            "holder_ticks": self.holder_ticks,
            "pass_completed_count": self.pass_completed_count,
            "goal_scored_count": self.goal_scored_count,
            "turnover_conceded_count": self.turnover_conceded_count,
            "pass_intercepted_count": self.pass_intercepted_count,
            "solitary_shot_count": self.solitary_shot_count,
            "assisted_goal_count": self.assisted_goal_count,
            "ball_hogging_count": self.ball_hogging_count,
        }

    def get_cumulative_diagnostics(self) -> Dict[str, Any]:
        """Return cumulative (cross-episode) event counters for live training logging."""
        return {
            "total_pass_completed_count": self.total_pass_completed_count,
            "total_goal_scored_count": self.total_goal_scored_count,
            "total_turnover_conceded_count": self.total_turnover_conceded_count,
        }

    def compute_shaped_rewards(
        self,
        base_rewards: Dict[str, float],
        step_events: List[Dict[str, Any]],
        info_ground_truth: Dict[str, Any],
        active_agents: List[str],
        actions: Optional[Dict[str, int]] = None,
    ) -> Dict[str, float]:
        """
        Calculates shaped rewards for all active left-team agents.
        Right-team agents (e.g. the defender in academy_rondo_4v1) are intentionally
        excluded because pass/assist/hogging terms are attacker-specific concepts.
        """
        shaped_rewards = {
            agent_id: base_rewards.get(agent_id, 0.0)
            for agent_id in active_agents
            if not agent_id.startswith("right_")
        }

        # Action cost: flat penalty for any ball-handling action to penalize spamming.
        BALL_ACTIONS = {9, 10, 11, 12, 17}
        if actions:
            for agent_id, action_idx in actions.items():
                if agent_id in shaped_rewards and action_idx in BALL_ACTIONS:
                    shaped_rewards[agent_id] -= 0.01

        # 1. Track Possession & Apply Ball-Hogging Penalties
        ball_owner = info_ground_truth.get("current_ball_owner") if info_ground_truth else None
        if isinstance(ball_owner, dict) and ball_owner.get("team") == "left":
            holder_id = ball_owner.get("agent_id")
            if holder_id and holder_id == self.current_holder_id:
                self.holder_ticks += 1
            else:
                self.current_holder_id = holder_id
                self.holder_ticks = 1

            if self.holder_ticks > self.max_hold_ticks and holder_id in shaped_rewards:
                shaped_rewards[holder_id] += self.p_ball_hogging
                self.ball_hogging_count += 1
        else:
            self.current_holder_id = None
            self.holder_ticks = 0

        # 2. Process Discrete Engine Events
        # M1: Some negative events are tagged team="right" by the engine because
        # the opposing team performed the interception/tackle/foul, but the
        # left-team agent identified in the event is the one who lost possession
        # and must receive the penalty. Process these regardless of event_team.
        _LEFT_TEAM_VICTIM_EVENT_TYPES = frozenset({
            "PASS_INTERCEPTED",
            "PASS_FAILED",
            "TURNOVER_CONCEDED",
        })
        for event in step_events:
            if not isinstance(event, dict):
                continue
            event_type = event.get("type")
            event_team = event.get("team")
            agent_id = event.get("agent_id")

            # M1: Negative events where left-team agent is the victim.
            if event_type in _LEFT_TEAM_VICTIM_EVENT_TYPES:
                if event_type == "PASS_INTERCEPTED":
                    self.pass_chain_length = 0
                    self.pass_intercepted_count += 1
                    self.total_turnover_conceded_count += 1
                    if agent_id in shaped_rewards:
                        shaped_rewards[agent_id] += self.p_turnover
                elif event_type in ("PASS_FAILED", "TURNOVER_CONCEDED"):
                    self.pass_chain_length = 0
                    self.turnover_conceded_count += 1
                    self.total_turnover_conceded_count += 1
                    if agent_id in shaped_rewards:
                        shaped_rewards[agent_id] += self.p_turnover
                continue

            # For all other events, only apply to left-team events.
            if event_team != "left":
                continue

            if event_type == "PASS_COMPLETED":
                self.pass_chain_length += 1
                self.pass_completed_count += 1
                self.total_pass_completed_count += 1
                if agent_id in shaped_rewards:
                    shaped_rewards[agent_id] += self.r_pass

            elif event_type == "SHOT_MISSED":
                if agent_id in shaped_rewards:
                    shaped_rewards[agent_id] -= 0.05

            elif event_type == "SHOT_TAKEN":
                # Penalize shots taken without a preceding completed pass in the
                # same possession chain (pass_chain_length == 0 => by definition
                # an unassisted shot; see test_solitary_shot_penalty_when_no_pass_chain).
                if self.pass_chain_length == 0:
                    # Attribution on the wire: the engine broadcasts the shot
                    # event on the frame the shot is released, when the ball is
                    # already in flight -- the bridge header then reports no ball
                    # owner (agent_id absent from the event). Fall back to charging
                    # every left-team agent that commanded a SHOT action this frame,
                    # so an unassisted-shot penalty cannot be dodged by spamming SHOT.
                    shot_agents: List[str] = []
                    if agent_id is not None and agent_id in shaped_rewards:
                        shot_agents = [agent_id]
                    elif actions:
                        shot_agents = [
                            act_agent
                            for act_agent, act_idx in actions.items()
                            if act_agent in shaped_rewards
                            and act_idx == SHOT_ACTION_ID
                        ]
                    for shot_agent in shot_agents:
                        shaped_rewards[shot_agent] += self.p_solitary_shot
                        self.solitary_shot_count += 1

            elif event_type == "GOAL_SCORED":
                # M2: The engine already provides the raw goal reward (e.g. +2.00)
                # in the step's base reward. Here we add the cooperative assisted-goal
                # bonus when the goal came from a pass chain.
                if self.pass_chain_length > 0:
                    for active_agent in active_agents:
                        if active_agent in shaped_rewards:
                            shaped_rewards[active_agent] += self.r_assisted_goal
                    self.assisted_goal_count += 1
                self.goal_scored_count += 1
                self.total_goal_scored_count += 1
                self.pass_chain_length = 0

        return shaped_rewards


