    @staticmethod
    def _graph_controlled_player_id(agent_id: str) -> str:
        """Map bridge IDs (left_1) to graph roster IDs (left_0)."""
        team, _, raw_index = agent_id.rpartition("_")
        if team not in ("left", "right") or not raw_index.isdigit():
            raise ValueError(f"Cannot map agent ID to graph roster: {agent_id!r}")
        index = int(raw_index)
        if index < 1:
            raise ValueError(f"Bridge agent IDs are one-based: {agent_id!r}")
        return f"{team}_{index - 1}"

    def _attach_graph_observations(
        self,
        observations: Dict[str, Any],
        infos: Dict[str, Any],
        scenario_id: Optional[str] = None,
    ) -> None:
        """Optionally attach a per-agent Phase 3 graph alongside flat observations.

        Standard PettingZoo reset/step responses store info by agent, while the
        batched helpers return one shared info dict. Both forms are supported.
        The existing observation and action-mask contract is left untouched.
        """
        if not self.include_graph_observations or not observations:
            return

        try:
            from training.gnn_graph_builder import SCENARIOS as GNN_SCENARIOS
            from training.gnn_graph_builder import build_graph
        except ImportError:
            from gnn_graph_builder import SCENARIOS as GNN_SCENARIOS
            from gnn_graph_builder import build_graph

        requested_scenario = scenario_id or self.scenario
        graph_scenario = requested_scenario
        if graph_scenario not in GNN_SCENARIOS and graph_scenario.endswith("_onball"):
            candidate = graph_scenario[: -len("_onball")]
            if candidate in GNN_SCENARIOS:
                graph_scenario = candidate
        if graph_scenario not in GNN_SCENARIOS:
            raise ValueError(
                f"Graph observations are not defined for scenario {requested_scenario!r}"
            )

        per_agent_infos = all(agent in infos for agent in observations)
        graph_by_agent: Dict[str, Any] = {}
        for agent_id, observation in observations.items():
            if isinstance(observation, dict) and "observation" in observation:
                graph_input = observation
            else:
                graph_input = {"observation": observation}
            info = infos[agent_id] if per_agent_infos else infos
            graph_info = dict(info) if isinstance(info, dict) else {}
            graph_info["controlledPlayerId"] = self._graph_controlled_player_id(agent_id)
            graph_by_agent[agent_id] = build_graph(
                graph_input, graph_info, graph_scenario
            )

        if per_agent_infos:
            for agent_id, graph in graph_by_agent.items():
                infos[agent_id]["graph_observation"] = graph
        else:
            infos["graph_observations"] = graph_by_agent

    def set_opponent_difficulty(self, difficulty: str) -> None:
        """Set the right-team (bot) difficulty via the bridge /opponent endpoint."""
        if difficulty not in ("easy", "medium", "hard", "master"):
            raise ValueError(f"Invalid opponent difficulty: {difficulty}")
        self.opponent_difficulty = difficulty
        try:
            import requests  # already a module dependency of this wrapper

            requests.post(
                f"http://{self.host}:{self.port}/opponent",
                json={"difficulty": difficulty},
                timeout=5.0,
            )
        except Exception:
            pass  # older bridges without /opponent keep the default difficulty

    def set_scenario(self, scenario: str) -> None:
        """Switch the active scenario and clear rollout state so the next reset uses it."""
        self.scenario = scenario
        if getattr(self, "enable_reward_shaping", False):
            # Reuse the existing adapter when the new scenario still maps to the
            # same adapter class (e.g. a curriculum promotion inside the 3v1
            # finishing family: academy_3_vs_1_defender_2 -> _keeper_aggressive).
            # reset() clears per-episode state but deliberately keeps the
            # run-scoped exploration visit counts. A cross-class switch (e.g.
            # attacking drill -> rondo) builds a fresh adapter instead.
            self.reward_adapter = self._scenario_adapter(
                previous=getattr(self, "reward_adapter", None)
            )
            if self.reward_adapter is not None:
                self.reward_shaper = self.reward_adapter
                print(f"[RewardAdapter] active={type(self.reward_adapter).__name__} scenario={scenario}", flush=True)
        # Clear MAPPO rollout scratch state so collect_rollout() re-initializes
        # from the new scenario rather than replaying stale observations.
        self._mappo_obs = None
        self._mappo_ep_rew = 0.0
        self._mappo_ep_len = 0
        self._pending_pass = None
        if hasattr(self, "_batch_envs"):
            self._batch_envs = []

    def _decode_reset_result(self, result: Dict[str, Any]) -> Dict[str, Any]:
        """Decode one reset response payload into a per-env rollout state dict."""
        info_data = result.get("info", {})
        controllable_ids = info_data.get("controllableAgentIds", [])
        if not controllable_ids:
            controlled_id = info_data.get("controlledPlayerId", "left_1")
            controllable_ids = [controlled_id]
        raw_obs_list = result.get("observations", [])
        if not raw_obs_list and "observation" in result:
            raw_obs_list = [result["observation"]]
        observations: Dict[str, np.ndarray] = {}
        for idx, agent in enumerate(controllable_ids):
            if idx < len(raw_obs_list):
                obs = np.array(raw_obs_list[idx], dtype=np.float32)
            else:
                obs = np.zeros(OBSERVATION_DIM, dtype=np.float32)
            observations[agent] = obs
        # Real reset-time legality masks from the bridge (masking gap, Part 1):
        # at kickoff the ball is unowned, so SHOT/PASS/DRIBBLE are illegal and
        # TACKLE is legal. Note: We now use a fail-closed fallback (IDLE + movement
        # only) for any missing/stale bridge mask, NOT all-ones. The all-ones fallback
        # was a legacy compatibility shim that silently failed open and violates the
        # fail-closed action-masking contract.
        raw_masks = result.get("action_masks") or info_data.get("action_masks")
        if raw_masks:
            action_masks = {
                agent: (
                    np.array(raw_masks[idx], dtype=np.int8)
                    if idx < len(raw_masks)
                    else _fail_closed_fallback_mask()
                )
                for idx, agent in enumerate(controllable_ids)
            }
        else:
            # Legacy/stale-bridge fallback: fail-closed, not all-ones.
            action_masks = {agent: _fail_closed_fallback_mask() for agent in controllable_ids}
        batched_obs = {
            agent: {"observation": observations[agent], "action_mask": action_masks[agent]}
            for agent in controllable_ids
        }
        # OCCUPANCY-EXP: capture true ball owner at reset from bridge response
        reset_ball_owner = info_data.get("current_ball_owner")
        return {
            "obs_dict": batched_obs,
            "action_masks": action_masks,
            "possible_agents": list(controllable_ids),
            "agents": list(controllable_ids),
            "agent_order": list(controllable_ids),
            "obs_dim": OBSERVATION_DIM,
            "ep_rew": 0.0,
            "ep_len": 0,
            "info": dict(info_data),
            "reset_ball_owner": reset_ball_owner,
        }

    def _scenario_adapter(self, previous: Optional[Any] = None) -> Optional[Any]:
        """Build the scenario reward adapter, preserving run-scoped state.

        This is the single construction point for scenario reward adapters.
        ``reset_batch()`` runs at the top of every ``collect_rollout_batched()``
        iteration and ``reset_one()`` fires on every episode terminal, so
        building a fresh adapter each time would wipe
        ``AttackingDrillRewardAdapter._visit_counts`` on every rollout — the
        count-based exploration bonus is only meaningful if counts accumulate
        over the training run.

        When ``previous`` is the same adapter class the current scenario
        requires, it is reused after ``reset()`` (which clears per-episode state
        but deliberately keeps visit counts). This mirrors the single-env path's
        ``env.reset() -> self.reward_adapter.reset()``. A scenario change that
        maps to a different adapter class (e.g. attacking drill -> rondo) builds
        a brand-new adapter, and ``__init__`` passes no ``previous``.

        Returns None when reward shaping is disabled or when the scenario has no
        adapter — logging a warning rather than swallowing the factory's loud
        ValueError, so a silently-degraded reward model is visible in the logs.
        """
        if not getattr(self, "enable_reward_shaping", False):
            return None
        try:
            from training.reward_adapters import get_reward_adapter
            candidate = get_reward_adapter(
                self.scenario,
                enable_exploration_bonus=getattr(self, "enable_exploration_bonus", True),
                exploration_beta=getattr(self, "exploration_beta", 0.03),
            )
        except Exception as exc:
            logger.warning(
                "[RewardAdapter] no adapter for scenario %r (%s); "
                "falling back to the legacy CooperativeRewardShaper",
                self.scenario,
                exc,
            )
            return None
        if previous is not None and type(previous) is type(candidate):
            previous.reset()
            chosen = previous
        else:
            chosen = candidate
        # Training-time shot-clock override (None = keep the adapter's default).
        # Re-applied on every construction and reuse so a scenario switch or a
        # curriculum promotion keeps the same clock policy.
        t_max_override = getattr(self, "shot_clock_t_max", None)
        if t_max_override is not None and hasattr(chosen, "t_max"):
            chosen.t_max = int(t_max_override)
        return chosen

    def _init_batch_envs(self, batch_results: List[Dict[str, Any]]) -> None:
        """Initialize per-env rollout state from a batch reset response.

        Adapters are REUSED per env index when the scenario's adapter class is
        unchanged (see ``_scenario_adapter``): ``reset_batch()`` is called at the
        top of every ``collect_rollout_batched()``, so constructing fresh
        adapters here would wipe run-scoped exploration visit counts on every
        rollout instead of every episode.
        """
        previous_envs = list(getattr(self, "_batch_envs", None) or [])
        self._batch_envs = []
        for env_idx, result in enumerate(batch_results):
            env_state = self._decode_reset_result(result)
            prev = previous_envs[env_idx] if env_idx < len(previous_envs) else None
            prev_adapter = prev.get("reward_adapter") if isinstance(prev, dict) else None
            # M5: Per-env reward-shaping state so the batched path applies the
            # same cooperative curriculum as the single-env path.
            env_state["pending_pass"] = None
            env_state["reward_shaper"] = CooperativeRewardShaper() if self.enable_reward_shaping else None
            env_state["reward_adapter"] = self._scenario_adapter(previous=prev_adapter)
            env_state["last_actions"] = {}
            # OCCUPANCY-EXP: capture true ball owner at reset for each sub-env
            reset_ball_owner = env_state.get("reset_ball_owner")
            if reset_ball_owner and isinstance(reset_ball_owner, dict):
                owner_id = reset_ball_owner.get("agent_id")
                if owner_id and owner_id in env_state["agents"]:
                    env_state["_last_ball_owner_agent_idx"] = env_state["agents"].index(owner_id)
                else:
                    env_state["_last_ball_owner_agent_idx"] = 255
            else:
                env_state["_last_ball_owner_agent_idx"] = 255
            self._batch_envs.append(env_state)

    def reset_batch(self, seeds: Optional[List[int]] = None) -> List[Tuple[Dict[str, np.ndarray], Dict[str, Any]]]:
        """Reset all sub-environments in the batch and return per-env (obs, info) tuples."""
        seeds = seeds or [42] * self.batch_size
        requests = []
        for idx, s in enumerate(seeds[: self.batch_size]):
            req: Dict[str, Any] = {"scenario": self.scenario}
            if s is not None:
                req["seed"] = int(s)
            else:
                req["seed"] = 42 + idx
            requests.append(req)
        while len(requests) < self.batch_size:
            requests.append({"scenario": self.scenario, "seed": 42 + len(requests)})
        payload = json.dumps({"type": "reset_batch", "environments": requests})
        if self.ws_client is None:
            self._connect_ws()
        try:
            self.ws_client.send(payload)
            data = self._recv_reset_batch_response()
        except Exception:
            self._connect_ws()
            self.ws_client.send(payload)
            data = self._recv_reset_batch_response()
        parsed = json.loads(data) if isinstance(data, str) else {}
        if not isinstance(parsed, dict):
            raise RuntimeError(f"[GMN-Batch] Expected dict reset response, got {type(parsed)}")
        results = parsed.get("results", [])
        if len(results) != self.batch_size:
            raise RuntimeError(f"[GMN-Batch] Expected {self.batch_size} reset results, got {len(results)}: {list(parsed.keys())}")
        self._init_batch_envs(results)
        # Return per-env tuples for the caller (trainer can index by env_idx)
        return [
            (env_state["obs_dict"], {a: env_state["info"] for a in env_state["agents"]})
            for env_state in self._batch_envs
        ]

    def reset_one(
        self, env_idx: int, seed: Optional[int] = None
    ) -> Tuple[Dict[str, np.ndarray], Dict[str, Any]]:
        """Reset a single sub-environment in the batch (G6 fix).

        Mirrors collect_rollout_parallel's reset-on-terminal: a terminated
        sub-env is revived immediately instead of idling until the whole batch
        is dead. Returns (obs_dict, info) in the same envelope format as
        reset_batch; self._batch_envs[env_idx] is replaced with fresh state.
        """
        if not (0 <= env_idx < self.batch_size):
            raise IndexError(
                f"[GMN-Batch] reset_one index {env_idx} out of range (batch_size={self.batch_size})"
            )
        payload = json.dumps({
            "type": "reset_one",
            "index": int(env_idx),
            "scenario": self.scenario,
            "seed": int(seed) if seed is not None else 42 + env_idx,
        })
        if self.ws_client is None:
            self._connect_ws()
        try:
            self.ws_client.send(payload)
            data = self._recv_reset_one_response()
        except Exception:
            self._connect_ws()
            self.ws_client.send(payload)
            data = self._recv_reset_one_response()
        parsed = json.loads(data) if isinstance(data, str) else {}
        if not isinstance(parsed, dict) or parsed.get("type") != "reset_one_result":
            raise RuntimeError(f"[GMN-Batch] Expected reset_one_result, got: {list(parsed.keys()) if isinstance(parsed, dict) else type(parsed)}")
        result = parsed.get("result")
        if not isinstance(result, dict):
            raise RuntimeError(f"[GMN-Batch] reset_one({env_idx}) missing result payload")
        state = self._decode_reset_result(result)
        # Preserve run-scoped adapter state across episode boundaries: reuse this
        # sub-env's existing adapter (after reset()) when the scenario still maps
        # to the same adapter class, so the count-based exploration visit counts
        # survive the reset instead of restarting every episode.
        prev = self._batch_envs[env_idx] if 0 <= env_idx < len(self._batch_envs) else None
        prev_adapter = prev.get("reward_adapter") if isinstance(prev, dict) else None
        state["pending_pass"] = None
        state["reward_shaper"] = CooperativeRewardShaper() if self.enable_reward_shaping else None
        state["reward_adapter"] = self._scenario_adapter(previous=prev_adapter)
        state["last_actions"] = {}
        # OCCUPANCY-EXP: capture true ball owner at reset for this sub-env
        reset_ball_owner = state.get("reset_ball_owner")
        if reset_ball_owner and isinstance(reset_ball_owner, dict):
            owner_id = reset_ball_owner.get("agent_id")
            if owner_id and owner_id in state["agents"]:
                state["_last_ball_owner_agent_idx"] = state["agents"].index(owner_id)
            else:
                state["_last_ball_owner_agent_idx"] = 255
        else:
            state["_last_ball_owner_agent_idx"] = 255
        self._batch_envs[env_idx] = state
        infos = {a: dict(state["info"]) for a in state["agents"]}
        self._attach_graph_observations(state["obs_dict"], infos)
        return (state["obs_dict"], infos)

    def _recv_reset_one_response(self) -> str:
        """Receive a reset_one JSON response, skipping unsolicited broadcast frames."""
        for _ in range(60):
            data = self._recv_frame("reset_one")
            if isinstance(data, str):
                try:
                    parsed = json.loads(data)
                    if isinstance(parsed, dict) and parsed.get("type") == "reset_one_result":
                        return data
                except (json.JSONDecodeError, AttributeError):
                    pass
        raise RuntimeError("[GMN-Batch] No reset_one_result received (only broadcast frames)")

    def step_batch(
        self, action_sets: List[Dict[str, int]]
    ) -> List[Tuple[Dict[str, np.ndarray], Dict[str, float], Dict[str, bool], Dict[str, bool], Dict[str, Any]]]:
        """Step all sub-environments with their respective action dicts."""
        if len(action_sets) != self.batch_size:
            raise RuntimeError(f"[GMN-Batch] step_batch expects {self.batch_size} action dicts, got {len(action_sets)}")
        action_bytes_per_env: List[bytes] = []
        controllable_ids_per_env: List[List[str]] = []
        for env_idx, actions in enumerate(action_sets):
            env_state = self._batch_envs[env_idx]
            current_agents = env_state["agents"]
            num_agents = len(current_agents)
            action_bytes = bytearray(num_agents)
            for i, agent in enumerate(current_agents):
                act = int(actions.get(agent, 0))
                if not (0 <= act < ACTION_SPACE_SIZE):
                    raise ValueError(f"[GMN-Batch] Invalid action {act} for agent {agent}")
                action_bytes[i] = act
            action_bytes_per_env.append(bytes(action_bytes))
            controllable_ids_per_env.append(current_agents)
            # M5: Store actions for reward-shaping attribution (solitary shot, etc.).
            env_state["last_actions"] = dict(actions)
        # Build batched binary frame: [0xFF (1B)] [B (1B)] [N (1B)] [B * N action bytes]
        N = len(controllable_ids_per_env[0]) if controllable_ids_per_env else 0
        frame = bytearray(3 + self.batch_size * N)
        frame[0] = 0xFF
        frame[1] = self.batch_size
        frame[2] = N
        for env_idx, action_bytes in enumerate(action_bytes_per_env):
            offset = 3 + env_idx * N
            frame[offset : offset + N] = action_bytes
        if self.ws_client is None:
            self._connect_ws()
        try:
            self.ws_client.send(bytes(frame))
            data = self._recv_batch_response()
        except Exception as e:
            # Log bridge errors for forensic debugging
            if getattr(self, "_forensic_debug", False):
                import sys as _sys
                print(
                    f"[FORENSIC_BRIDGE_ERROR]\n"
                    f"scenario={self.scenario}\n"
                    f"global_step={self._step_count}\n"
                    f"error_type={type(e).__name__}\n"
                    f"error_message={str(e)}\n"
                    f"bridge_error_count={getattr(self, '_bridge_error_count', 0)}\n"
                    f"batch_size={self.batch_size}\n"
                    f"[END_FORENSIC_BRIDGE_ERROR]",
                    flush=True,
                    file=_sys.stderr,
                )
            self._connect_ws()
            self.ws_client.send(bytes(frame))
            data = self._recv_batch_response()
        if isinstance(data, str):
            raise RuntimeError(f"[GMN-Batch] Bridge sent text error: {data}")
        obs_bytes = OBSERVATION_DIM * 4
        is_rondo = self.scenario == "academy_rondo_4v1"
        header_size = 22 if is_rondo else 18
        mask_bytes = 19
        frame_size = header_size + obs_bytes * N + mask_bytes * N
        expected_len = 2 + self.batch_size * frame_size
        if len(data) != expected_len:
            raise RuntimeError(
                f"[GMN-Batch Frame Length Error] Expected {expected_len} bytes, got {len(data)} bytes"
            )
        results: List[Tuple[Dict[str, np.ndarray], Dict[str, float], Dict[str, bool], Dict[str, bool], Dict[str, Any]]] = []
        for env_idx in range(self.batch_size):
            env_state = self._batch_envs[env_idx]
            base_offset = 2 + env_idx * frame_size
            reward, term, trunc, score_l, score_r, cp_reward, dist_goal, event_code, ball_owner_agent_idx = struct.unpack_from(
                "<f??BBffBB", data, base_offset
            )
            # Bridge error-frame sentinel (P0 #5): surface loudly instead of silently
            # accumulating a -999 penalty into episode reward.
            if float(reward) <= -998.0 and bool(term):
                self._bridge_error_count += 1
                raise RuntimeError(
                    f"[GMN-PettingZoo Bridge Error] Bridge returned an error frame for "
                    f"env_idx={env_idx} (reward <= -998.0, terminated=true). This "
                    f"indicates an internal bridge error. Check the bridge server logs."
                )
            defender_reward = 0.0
            if is_rondo:
                defender_reward = struct.unpack_from("<f", data, base_offset + 18)[0]
            shared_reward = float(reward)
            shared_term = bool(term)
            shared_trunc = bool(trunc)
            shared_info: Dict[str, Any] = {
                "score": {"left": int(score_l), "right": int(score_r)},
                "checkpointReward": float(cp_reward),
                "ballDistanceToGoal": float(dist_goal),
                "eventCode": int(event_code),
                "step": env_state.get("ep_len", 0),
            }
            if 0 < event_code < len(EVENT_CODE_MAP):
                ev_type = EVENT_CODE_MAP[event_code]
                if ev_type:
                    shared_info["event"] = {"type": ev_type}
            observations: Dict[str, Any] = {}
            action_masks: Dict[str, np.ndarray] = {}
            terminal_agents = list(env_state["agents"])
            for i, agent in enumerate(terminal_agents):
                offset = base_offset + header_size + i * obs_bytes
                obs = np.frombuffer(data, dtype="<f4", count=OBSERVATION_DIM, offset=offset).copy()
                mask_offset = base_offset + header_size + N * obs_bytes + i * 19
                mask = np.frombuffer(data, dtype="<u1", count=19, offset=mask_offset).copy().astype(np.int8)
                observations[agent] = {"observation": obs, "action_mask": mask}
                action_masks[agent] = mask
            batched_obs = {
                agent: {"observation": observations[agent]["observation"], "action_mask": action_masks[agent]}
                for agent in terminal_agents
            }
            env_state["obs_dict"] = batched_obs
            env_state["action_masks"] = action_masks
            # Extract absolute ball position AND nearest-left-agent distance
            # from the first agent's observation (obs indices 88, 89 for ball
            # and 0..21 for left-player positions per
            # src/engine/ObservationEncoder.ts). Shared by all agents.
            _ball_x: Optional[float] = None
            _ball_y: Optional[float] = None
            _nearest_left_dist: Optional[float] = None
            if terminal_agents:
                _first_obs = observations.get(terminal_agents[0], {}).get("observation")
                if _first_obs is not None and len(_first_obs) > 89:
                    _ball_x = float(_first_obs[88])
                    _ball_y = float(_first_obs[89])
                    # Single source of truth for the proximity math, shared with
                    # the single-env step path. Never raises; returns None when
                    # the observation is unusable.
                    _nearest_left_dist = _nearest_left_agent_ball_distance(
                        _ball_x, _ball_y, _first_obs
                    )
            env_state["_ball_x"] = _ball_x
            env_state["_ball_y"] = _ball_y
            env_state["_nearest_left_dist"] = _nearest_left_dist
            env_state["ep_rew"] += shared_reward
            env_state["ep_len"] += 1
            if shared_term or shared_trunc:
                env_state["agents"] = []
                shared_info["episode_length_steps"] = env_state.get("ep_len", 0)
                shared_info["episode_physics_ticks"] = env_state.get("ep_len", 0)
            if is_rondo:
                env_rewards = {
                    agent: defender_reward if agent.startswith("right_") else shared_reward
                    for agent in terminal_agents
                }
            else:
                # M5: Normalize non-rondo rewards to a per-agent dict so shaping
                # can add cooperative bonuses on top.
                env_rewards = {agent: shared_reward for agent in terminal_agents}

            # M5: Apply cooperative reward shaping per sub-environment so the
            # batched path exercises the same curriculum as the single-env path.
            shaped_rewards, timeout_penalty = self._apply_shaping_for_env(
                env_state=env_state,
                shared_reward=shared_reward,
                shared_term=shared_term,
                shared_trunc=shared_trunc,
                event_code=event_code,
                ball_owner_agent_idx=ball_owner_agent_idx,
                score_l=score_l,
                score_r=score_r,
                actions=env_state.get("last_actions", {}),
                dist_goal=float(dist_goal),
            )
            if timeout_penalty is not None:
                # Shot-clock fired for this sub-env: apply the penalty on top of
                # the shaped rewards so the -0.5 is not lost. Truncation is
                # opt-in (shot_clock_truncates): when False the episode stays
                # alive and only the penalty lands, so long-horizon training is
                # not capped at ~t_max ticks. When True, mark the episode
                # truncated (not terminated) so GAE bootstraps the value function.
                for agent in terminal_agents:
                    if agent in env_rewards and agent in shaped_rewards:
                        env_rewards[agent] = shaped_rewards[agent] + timeout_penalty
                if getattr(self, "shot_clock_truncates", True):
                    shared_trunc = True
                    shared_info["episode_length_steps"] = env_state.get("ep_len", 0)
                    shared_info["episode_physics_ticks"] = env_state.get("ep_len", 0)
                    env_state["agents"] = []
            if shaped_rewards and timeout_penalty is None:
                for agent in terminal_agents:
                    if agent in shaped_rewards:
                        env_rewards[agent] = shaped_rewards[agent]

            self._attach_graph_observations(observations, shared_info)
            results.append((observations, env_rewards, shared_term, shared_trunc, shared_info))
        return results

