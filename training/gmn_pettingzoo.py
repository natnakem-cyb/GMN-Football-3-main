class GMNMultiAgentEnv(ParallelEnv):
    """
    PettingZoo ParallelEnv wrapper for GMN-Football-3 multi-agent scenarios.
    Controls N players on the left team simultaneously.
    """

    metadata = {
        "render_modes": ["human", "rgb_array"],
        "name": "gmn_football_multiagent_v3",
    }

    def __init__(
        self,
        scenario: str = "academy_3_vs_1_with_keeper",
        host: str = "127.0.0.1",
        port: Optional[int] = None,
        auto_start_bridge: bool = True,
        render_mode: Optional[str] = None,
        enable_reward_shaping: bool = True,
        opponent_difficulty: str = "medium",
        opponent_pool: Optional[Any] = None,
        batch_size: int = 1,
        debug_rewards: bool = False,
    ):
        super().__init__()
        self.scenario = scenario
        self.host = host
        self.port = port or int(os.environ.get("GMN_BRIDGE_PORT", "5050"))
        self.base_url = f"http://{self.host}:{self.port}"
        self.ws_url = f"ws://{self.host}:{self.port}"
        if debug_rewards:
            self.ws_url += "?debug=rewards"
        self.auto_start_bridge = auto_start_bridge
        self.render_mode = render_mode
        self.enable_reward_shaping = enable_reward_shaping
        self.opponent_difficulty = opponent_difficulty
        self.opponent_pool = opponent_pool
        self.current_opponent: Optional[Dict[str, Any]] = None
        self.batch_size = max(1, int(batch_size))
        self.debug_rewards = debug_rewards
        self.reward_components: List[Dict[str, Any]] = []
        self.bridge_process: Optional[subprocess.Popen] = None
        self.ws_client = None
        self.reward_shaper = CooperativeRewardShaper() if enable_reward_shaping else None
        self._pending_pass: Optional[Dict[str, Any]] = None
        # Per-env rollout state for batched mode: list of dicts with keys
        # obs_dict, ep_rew, ep_len, agents, possible_agents, agent_order, obs_dim
        self._batch_envs: List[Dict[str, Any]] = []

        self._step_count = 0
        self.agents: List[str] = []
        self.possible_agents: List[str] = []

        # Phase 5: forensic debug flag and episode index
        self._forensic_debug: bool = os.environ.get("GMN_FORENSIC_DEBUG", "0") == "1"
        self._episode_index: int = 0
        self._bridge_error_count: int = 0

        # Terminal-frame provenance for forensic reward tracing (Step 2/3).
        # These are set on every step() call; on terminal ticks they capture
        # the exact values that flowed through the pipeline at episode end.
        self._last_frame_reward: float = 0.0
        self._last_frame_event_code: int = 0
        self._last_frame_score: Dict[str, int] = {"left": 0, "right": 0}
        self._last_shared_reward: float = 0.0

        # Observation and action spaces (identical across all agents)
        self._obs_space = spaces.Dict({
            "observation": spaces.Box(
                low=-100.0,
                high=100.0,
                shape=(OBSERVATION_DIM,),
                dtype=np.float32,
            ),
            "action_mask": spaces.Box(
                low=0,
                high=1,
                shape=(19,),
                dtype=np.int8,
            ),
        })
        self._act_space = spaces.Discrete(ACTION_SPACE_SIZE)

        # Ensure Bridge Server is running & connected
        self._ensure_bridge_running()
        # P0 #6: bounded WS receive timeout (never hang on a missing frame).
        self.ws_recv_timeout = float(os.environ.get("GMN_WS_RECV_TIMEOUT", "10.0"))
        if self.auto_start_bridge:
            self._connect_ws()

        # Perform initial reset to discover controllable agents.
        # When auto_start_bridge=False (e.g. unit tests injecting a mock WS),
        # skip reset so ws_client stays None until the caller sets it.
        if self.auto_start_bridge:
            self.reset()

        # Set opponent difficulty AFTER bridge is fully ready and connected.
        # Calling before _connect_ws() can fail silently if the bridge was just
        # started and its /opponent endpoint is not yet accepting requests.
        if opponent_difficulty != "medium":
            self.set_opponent_difficulty(opponent_difficulty)

    def set_opponent_difficulty(self, difficulty: str) -> None:
        """Set the right-team (bot) difficulty via the bridge /opponent endpoint."""
        if difficulty not in ("easy", "medium", "hard", "master"):
            raise ValueError(f"Invalid opponent difficulty: {difficulty}")
        self.opponent_difficulty = difficulty
        try:
            import requests  # already a module dependency of this wrapper

            requests.post(
                f"http://{self.host}:{self.port}/opponent",
                json={"difficulty": difficulty},
                timeout=5.0,
            )
        except Exception:
            pass  # older bridges without /opponent keep the default difficulty

    def set_scenario(self, scenario: str) -> None:
        """Switch the active scenario and clear rollout state so the next reset uses it."""
        self.scenario = scenario
        # Clear MAPPO rollout scratch state so collect_rollout() re-initializes
        # from the new scenario rather than replaying stale observations.
        self._mappo_obs = None
        self._mappo_ep_rew = 0.0
        self._mappo_ep_len = 0
        self._pending_pass = None
        if hasattr(self, "_batch_envs"):
            self._batch_envs = []

    def _decode_reset_result(self, result: Dict[str, Any]) -> Dict[str, Any]:
        """Decode one reset response payload into a per-env rollout state dict."""
        info_data = result.get("info", {})
        controllable_ids = info_data.get("controllableAgentIds", [])
        if not controllable_ids:
            controlled_id = info_data.get("controlledPlayerId", "left_1")
            controllable_ids = [controlled_id]
        raw_obs_list = result.get("observations", [])
        if not raw_obs_list and "observation" in result:
            raw_obs_list = [result["observation"]]
        observations: Dict[str, np.ndarray] = {}
        for idx, agent in enumerate(controllable_ids):
            if idx < len(raw_obs_list):
                obs = np.array(raw_obs_list[idx], dtype=np.float32)
            else:
                obs = np.zeros(OBSERVATION_DIM, dtype=np.float32)
            observations[agent] = obs
        action_masks = {agent: np.ones(19, dtype=np.int8) for agent in controllable_ids}
        batched_obs = {
            agent: {"observation": observations[agent], "action_mask": action_masks[agent]}
            for agent in controllable_ids
        }
        return {
            "obs_dict": batched_obs,
            "action_masks": action_masks,
            "possible_agents": list(controllable_ids),
            "agents": list(controllable_ids),
            "agent_order": list(controllable_ids),
            "obs_dim": OBSERVATION_DIM,
            "ep_rew": 0.0,
            "ep_len": 0,
            "info": dict(info_data),
        }

    def _init_batch_envs(self, batch_results: List[Dict[str, Any]]) -> None:
        """Initialize per-env rollout state from a batch reset response."""
        self._batch_envs = []
        for result in batch_results:
            env_state = self._decode_reset_result(result)
            # M5: Per-env reward-shaping state so the batched path applies the
            # same cooperative curriculum as the single-env path.
            env_state["pending_pass"] = None
            env_state["reward_shaper"] = CooperativeRewardShaper() if self.enable_reward_shaping else None
            env_state["last_actions"] = {}
            self._batch_envs.append(env_state)

    def reset_batch(self, seeds: Optional[List[int]] = None) -> List[Tuple[Dict[str, np.ndarray], Dict[str, Any]]]:
        """Reset all sub-environments in the batch and return per-env (obs, info) tuples."""
        seeds = seeds or [42] * self.batch_size
        requests = []
        for idx, s in enumerate(seeds[: self.batch_size]):
            req: Dict[str, Any] = {"scenario": self.scenario}
            if s is not None:
                req["seed"] = int(s)
            else:
                req["seed"] = 42 + idx
            requests.append(req)
        while len(requests) < self.batch_size:
            requests.append({"scenario": self.scenario, "seed": 42 + len(requests)})
        payload = json.dumps({"type": "reset_batch", "environments": requests})
        if self.ws_client is None:
            self._connect_ws()
        try:
            self.ws_client.send(payload)
            data = self._recv_reset_batch_response()
        except Exception:
            self._connect_ws()
            self.ws_client.send(payload)
            data = self._recv_reset_batch_response()
        parsed = json.loads(data) if isinstance(data, str) else {}
        if not isinstance(parsed, dict):
            raise RuntimeError(f"[GMN-Batch] Expected dict reset response, got {type(parsed)}")
        results = parsed.get("results", [])
        if len(results) != self.batch_size:
            raise RuntimeError(f"[GMN-Batch] Expected {self.batch_size} reset results, got {len(results)}: {list(parsed.keys())}")
        self._init_batch_envs(results)
        # Return per-env tuples for the caller (trainer can index by env_idx)
        return [
            (env_state["obs_dict"], {a: env_state["info"] for a in env_state["agents"]})
            for env_state in self._batch_envs
        ]

    def reset_one(
        self, env_idx: int, seed: Optional[int] = None
    ) -> Tuple[Dict[str, np.ndarray], Dict[str, Any]]:
        """Reset a single sub-environment in the batch (G6 fix).

        Mirrors collect_rollout_parallel's reset-on-terminal: a terminated
        sub-env is revived immediately instead of idling until the whole batch
        is dead. Returns (obs_dict, info) in the same envelope format as
        reset_batch; self._batch_envs[env_idx] is replaced with fresh state.
        """
        if not (0 <= env_idx < self.batch_size):
            raise IndexError(
                f"[GMN-Batch] reset_one index {env_idx} out of range (batch_size={self.batch_size})"
            )
        payload = json.dumps({
            "type": "reset_one",
            "index": int(env_idx),
            "scenario": self.scenario,
            "seed": int(seed) if seed is not None else 42 + env_idx,
        })
        if self.ws_client is None:
            self._connect_ws()
        try:
            self.ws_client.send(payload)
            data = self._recv_reset_one_response()
        except Exception:
            self._connect_ws()
            self.ws_client.send(payload)
            data = self._recv_reset_one_response()
        parsed = json.loads(data) if isinstance(data, str) else {}
        if not isinstance(parsed, dict) or parsed.get("type") != "reset_one_result":
            raise RuntimeError(f"[GMN-Batch] Expected reset_one_result, got: {list(parsed.keys()) if isinstance(parsed, dict) else type(parsed)}")
        result = parsed.get("result")
        if not isinstance(result, dict):
            raise RuntimeError(f"[GMN-Batch] reset_one({env_idx}) missing result payload")
        state = self._decode_reset_result(result)
        self._batch_envs[env_idx] = state
        return (state["obs_dict"], {a: state["info"] for a in state["agents"]})

    def _recv_reset_one_response(self) -> str:
        """Receive a reset_one JSON response, skipping unsolicited broadcast frames."""
        for _ in range(60):
            data = self._recv_frame("reset_one")
            if isinstance(data, str):
                try:
                    parsed = json.loads(data)
                    if isinstance(parsed, dict) and parsed.get("type") == "reset_one_result":
                        return data
                except (json.JSONDecodeError, AttributeError):
                    pass
        raise RuntimeError("[GMN-Batch] No reset_one_result received (only broadcast frames)")

    def step_batch(
        self, action_sets: List[Dict[str, int]]
    ) -> List[Tuple[Dict[str, np.ndarray], Dict[str, float], Dict[str, bool], Dict[str, bool], Dict[str, Any]]]:
        """Step all sub-environments with their respective action dicts."""
        if len(action_sets) != self.batch_size:
            raise RuntimeError(f"[GMN-Batch] step_batch expects {self.batch_size} action dicts, got {len(action_sets)}")
        action_bytes_per_env: List[bytes] = []
        controllable_ids_per_env: List[List[str]] = []
        for env_idx, actions in enumerate(action_sets):
            env_state = self._batch_envs[env_idx]
            current_agents = env_state["agents"]
            num_agents = len(current_agents)
            action_bytes = bytearray(num_agents)
            for i, agent in enumerate(current_agents):
                act = int(actions.get(agent, 0))
                if not (0 <= act < ACTION_SPACE_SIZE):
                    raise ValueError(f"[GMN-Batch] Invalid action {act} for agent {agent}")
                action_bytes[i] = act
            action_bytes_per_env.append(bytes(action_bytes))
            controllable_ids_per_env.append(current_agents)
            # M5: Store actions for reward-shaping attribution (solitary shot, etc.).
            env_state["last_actions"] = dict(actions)
        # Build batched binary frame: [0xFF (1B)] [B (1B)] [N (1B)] [B * N action bytes]
        N = len(controllable_ids_per_env[0]) if controllable_ids_per_env else 0
        frame = bytearray(3 + self.batch_size * N)
        frame[0] = 0xFF
        frame[1] = self.batch_size
        frame[2] = N
        for env_idx, action_bytes in enumerate(action_bytes_per_env):
            offset = 3 + env_idx * N
            frame[offset : offset + N] = action_bytes
        if self.ws_client is None:
            self._connect_ws()
        try:
            self.ws_client.send(bytes(frame))
            data = self._recv_batch_response()
        except Exception as e:
            # Log bridge errors for forensic debugging
            if getattr(self, "_forensic_debug", False):
                import sys as _sys
                print(
                    f"[FORENSIC_BRIDGE_ERROR]\n"
                    f"scenario={self.scenario}\n"
                    f"global_step={self._step_count}\n"
                    f"error_type={type(e).__name__}\n"
                    f"error_message={str(e)}\n"
                    f"bridge_error_count={getattr(self, '_bridge_error_count', 0)}\n"
                    f"batch_size={self.batch_size}\n"
                    f"[END_FORENSIC_BRIDGE_ERROR]",
                    flush=True,
                    file=_sys.stderr,
                )
            self._connect_ws()
            self.ws_client.send(bytes(frame))
            data = self._recv_batch_response()
        if isinstance(data, str):
            raise RuntimeError(f"[GMN-Batch] Bridge sent text error: {data}")
        obs_bytes = OBSERVATION_DIM * 4
        is_rondo = self.scenario == "academy_rondo_4v1"
        header_size = 22 if is_rondo else 18
        mask_bytes = 19
        frame_size = header_size + obs_bytes * N + mask_bytes * N
        expected_len = 2 + self.batch_size * frame_size
        if len(data) != expected_len:
            raise RuntimeError(
                f"[GMN-Batch Frame Length Error] Expected {expected_len} bytes, got {len(data)} bytes"
            )
        results: List[Tuple[Dict[str, np.ndarray], Dict[str, float], Dict[str, bool], Dict[str, bool], Dict[str, Any]]] = []
        for env_idx in range(self.batch_size):
            env_state = self._batch_envs[env_idx]
            base_offset = 2 + env_idx * frame_size
            reward, term, trunc, score_l, score_r, cp_reward, dist_goal, event_code, ball_owner_agent_idx = struct.unpack_from(
                "<f??BBffBB", data, base_offset
            )
            # Bridge error-frame sentinel (P0 #5): surface loudly instead of silently
            # accumulating a -999 penalty into episode reward.
            if float(reward) <= -998.0 and bool(term):
                self._bridge_error_count += 1
                raise RuntimeError(
                    f"[GMN-PettingZoo Bridge Error] Bridge returned an error frame for "
                    f"env_idx={env_idx} (reward <= -998.0, terminated=true). This "
                    f"indicates an internal bridge error. Check the bridge server logs."
                )
            defender_reward = 0.0
            if is_rondo:
                defender_reward = struct.unpack_from("<f", data, base_offset + 18)[0]
            shared_reward = float(reward)
            shared_term = bool(term)
            shared_trunc = bool(trunc)
            shared_info: Dict[str, Any] = {
                "score": {"left": int(score_l), "right": int(score_r)},
                "checkpointReward": float(cp_reward),
                "ballDistanceToGoal": float(dist_goal),
                "eventCode": int(event_code),
                "step": env_state.get("ep_len", 0),
            }
            if 0 < event_code < len(EVENT_CODE_MAP):
                ev_type = EVENT_CODE_MAP[event_code]
                if ev_type:
                    shared_info["event"] = {"type": ev_type}
            observations: Dict[str, Any] = {}
            action_masks: Dict[str, np.ndarray] = {}
            terminal_agents = list(env_state["agents"])
            for i, agent in enumerate(terminal_agents):
                offset = base_offset + header_size + i * obs_bytes
                obs = np.frombuffer(data, dtype="<f4", count=OBSERVATION_DIM, offset=offset).copy()
                mask_offset = base_offset + header_size + N * obs_bytes + i * 19
                mask = np.frombuffer(data, dtype="<u1", count=19, offset=mask_offset).copy().astype(np.int8)
                observations[agent] = {"observation": obs, "action_mask": mask}
                action_masks[agent] = mask
            batched_obs = {
                agent: {"observation": observations[agent]["observation"], "action_mask": action_masks[agent]}
                for agent in terminal_agents
            }
            env_state["obs_dict"] = batched_obs
            env_state["action_masks"] = action_masks
            env_state["ep_rew"] += shared_reward
            env_state["ep_len"] += 1
            if shared_term or shared_trunc:
                env_state["agents"] = []
                shared_info["episode_length_steps"] = env_state.get("ep_len", 0)
                shared_info["episode_physics_ticks"] = env_state.get("ep_len", 0)
            if is_rondo:
                env_rewards = {
                    agent: defender_reward if agent.startswith("right_") else shared_reward
                    for agent in terminal_agents
                }
            else:
                # M5: Normalize non-rondo rewards to a per-agent dict so shaping
                # can add cooperative bonuses on top.
                env_rewards = {agent: shared_reward for agent in terminal_agents}

            # M5: Apply cooperative reward shaping per sub-environment so the
            # batched path exercises the same curriculum as the single-env path.
            shaped_rewards = self._apply_shaping_for_env(
                env_state=env_state,
                shared_reward=shared_reward,
                shared_term=shared_term,
                shared_trunc=shared_trunc,
                event_code=event_code,
                ball_owner_agent_idx=ball_owner_agent_idx,
                score_l=score_l,
                score_r=score_r,
                actions=env_state.get("last_actions", {}),
            )
            if shaped_rewards:
                for agent in terminal_agents:
                    if agent in shaped_rewards:
                        env_rewards[agent] = shaped_rewards[agent]

            results.append((observations, env_rewards, shared_term, shared_trunc, shared_info))
        return results

    def _recv_batch_response(self) -> bytes:
        """Receive one batched binary step response, skipping unsolicited broadcast frames."""
        for _ in range(60):
            data = self._recv_frame("step_batch")
            if isinstance(data, (bytes, bytearray)):
                return bytes(data)
        raise RuntimeError("[GMN-Batch] No binary batch response received (only broadcast frames)")

    def _recv_reset_batch_response(self) -> str:
        """Receive a reset_batch JSON response, skipping unsolicited broadcast frames."""
        for _ in range(60):
            data = self._recv_frame("reset_batch")
            if isinstance(data, str):
                try:
                    parsed = json.loads(data)
                    if isinstance(parsed, dict) and parsed.get("type") == "reset_batch_result":
                        return data
                except (json.JSONDecodeError, AttributeError):
                    pass
        raise RuntimeError("[GMN-Batch] No reset_batch_result received (only broadcast frames)")

    def _ensure_bridge_running(self):
        """Verifies connection to bridge server or starts it via npx tsx."""
        for attempt in range(6):
            try:
                res = requests.get(f"{self.base_url}/health", timeout=1.0)
                if res.status_code == 200:
                    info = res.json()
                    bridge_obs_dim = info.get("observation_dim", 115)
                    bridge_act_dim = info.get("action_space_size", info.get("action_dim", 19))
                    if bridge_obs_dim != OBSERVATION_DIM or bridge_act_dim != ACTION_SPACE_SIZE:
                        raise RuntimeError(
                            f"[GMN-PettingZoo Contract Mismatch] Bridge reports obs_dim={bridge_obs_dim}, "
                            f"act_dim={bridge_act_dim}; Expected obs_dim={OBSERVATION_DIM}, act_dim={ACTION_SPACE_SIZE}."
                        )
                    return
            except requests.RequestException:
                pass

            if self.auto_start_bridge and self.bridge_process is None:
                print(f"[GMN-PettingZoo] Launching Headless Bridge Server on {self.base_url}...")
                bridge_script = os.path.join(os.path.dirname(__file__), "bridge_server.ts")
                self.bridge_process = subprocess.Popen(
                    _npx_cmd() + ["tsx", bridge_script],
                    env=dict(os.environ, GMN_BRIDGE_PORT=str(self.port)),
                )
                time.sleep(2.0)
            else:
                time.sleep(1.0)


    def _connect_ws(self):
        """Establishes or reconnects WebSocket client connection."""
        if self.ws_client is not None:
            try:
                self.ws_client.close()
            except Exception:
                pass
        self.ws_client = websockets.sync.client.connect(
            self.ws_url, max_size=None, ping_interval=None, open_timeout=5.0
        )

    def _recv_frame(self, operation: str):
        """
        P0 #6: Receive one WebSocket frame with a bounded timeout. Raises a
        clear RuntimeError (with operation context) on timeout instead of
        blocking forever. No automatic retries (a retried step could duplicate
        an environment transition).
        """
        if self.ws_client is None:
            raise RuntimeError(f"[GMN-PettingZoo WS Error] No WebSocket connection during '{operation}'.")
        try:
            return self.ws_client.recv(timeout=self.ws_recv_timeout)
        except TimeoutError:
            raise RuntimeError(
                f"[GMN-PettingZoo WS Timeout] No frame received within {self.ws_recv_timeout}s "
                f"during '{operation}'. The bridge server is unresponsive."
            ) from None
        except RuntimeError as e:
            if "timed out" in str(e).lower():
                raise RuntimeError(
                    f"[GMN-PettingZoo WS Timeout] No frame received within {self.ws_recv_timeout}s "
                    f"during '{operation}'. The bridge server is unresponsive."
                ) from None
            raise RuntimeError(f"[GMN-PettingZoo WS Error] during '{operation}': {e}") from e
        except Exception as e:
            raise RuntimeError(f"[GMN-PettingZoo WS Error] during '{operation}': {e}") from e

