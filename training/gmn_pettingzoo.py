    def _recv_reset_response(self) -> Dict[str, Any]:
        """Receive a reset response, skipping unsolicited broadcast frames ON the shared WS.

        P1 #13: structural validation — a valid reset response must contain
        'observation' or 'observations' with the correct OBSERVATION_DIM shape.
        """
        for _ in range(60):
            frame = self._recv_frame("reset")
            if isinstance(frame, str):
                try:
                    candidate = json.loads(frame)
                except json.JSONDecodeError:
                    continue
                if self._is_valid_reset_response(candidate):
                    return candidate
            # unsolicited broadcast / malformed frame — skip
        raise RuntimeError("[GMN-PettingZoo] No structurally valid reset response received (only broadcast frames)")

    @staticmethod
    def _is_valid_reset_response(candidate: Any) -> bool:
        """P1 #13: structural validation of a reset response payload."""
        if not isinstance(candidate, dict):
            return False
        obs = candidate.get("observation")
        if isinstance(obs, (list, tuple)) and len(obs) == OBSERVATION_DIM:
            return True
        observations = candidate.get("observations")
        if (
            isinstance(observations, (list, tuple))
            and len(observations) > 0
            and all(isinstance(o, (list, tuple)) and len(o) == OBSERVATION_DIM for o in observations)
        ):
            return True
        return False

    def _recv_step_response(self, num_agents: int) -> Tuple[bytes, Optional[Dict[str, Any]], float]:
        """Receive a binary step response, skipping unsolicited broadcast frames ON the shared WS.
        
        Also collects any EPISODE_STATS JSON frames that arrive alongside the binary response.
        Returns (binary_data, episode_stats, defender_reward).
        """
        obs_bytes = OBSERVATION_DIM * 4
        is_rondo = self.scenario == "academy_rondo_4v1"
        header_size = 22 if is_rondo else 18
        mask_bytes = 19
        expected_len = header_size + obs_bytes * num_agents + mask_bytes * num_agents
        episode_stats: Optional[Dict[str, Any]] = None
        defender_reward = 0.0
        reward_components: Optional[Dict[str, Any]] = None
        for _ in range(60):
            data = self._recv_frame("step")
            if isinstance(data, (bytes, bytearray)) and len(data) == expected_len:
                # Phase 1: forensic binary terminal-frame capture
                raw_reward, term, trunc, score_l, score_r, cp_reward, dist_goal, event_code, ball_owner_agent_idx = struct.unpack_from(
                    "<f??BBffBB", data, 0
                )
                if is_rondo:
                    defender_reward = struct.unpack_from("<f", data, 18)[0]
                if getattr(self, "_forensic_debug", False) and (term or trunc):
                    print(
                        f"[FORENSIC_BINARY_TERMINAL]\n"
                        f"scenario={self.scenario}\n"
                        f"episode={getattr(self, '_episode_index', -1)}\n"
                        f"global_step={self._step_count}\n"
                        f"frame_length={len(data)}\n"
                        f"expected_frame_length={expected_len}\n"
                        f"\n"
                        f"raw_reward={raw_reward}\n"
                        f"terminated={bool(term)}\n"
                        f"truncated={bool(trunc)}\n"
                        f"\n"
                        f"score_left={score_l}\n"
                        f"score_right={score_r}\n"
                        f"\n"
                        f"checkpoint_reward={cp_reward}\n"
                        f"distance_to_goal={dist_goal}\n"
                        f"event_code={event_code}\n"
                        f"ball_owner_agent_idx={ball_owner_agent_idx}\n"
                        f"\n"
                        f"defender_reward={defender_reward}\n"
                        f"parsed_observation_offset={header_size}\n"
                        f"reward_offset=0\n"
                        f"{'ATTACKER_REWARD_FROM_OFFSET_0' if is_rondo else 'STANDARD_REWARD_FROM_OFFSET_0'}\n"
                        f"{'DEFENDER_REWARD_FROM_OFFSET_18' if is_rondo else 'NON_RONDO_NO_DEFENDER_FIELD'}\n"
                        f"[END_FORENSIC_BINARY_TERMINAL]",
                        flush=True,
                    )
                if self.debug_rewards and reward_components is None:
                    reward_components = {}
                return bytes(data), episode_stats, defender_reward, reward_components
            # Collect EPISODE_STATS and REWARD_COMPONENTS JSON frames
            if isinstance(data, str):
                try:
                    parsed = json.loads(data)
                    if isinstance(parsed, dict):
                        if parsed.get("type") == "EPISODE_STATS":
                            episode_stats = parsed
                            continue
                        if parsed.get("type") == "REWARD_COMPONENTS":
                            reward_components = parsed.get("data")
                            continue
                except (json.JSONDecodeError, AttributeError):
                    pass
            # unsolicited broadcast (training_status/telemetry) — skip
        raise RuntimeError(
            f"[GMN-PettingZoo Frame Length Error] Expected {expected_len} bytes, got only broadcast frames"
        )

    def reset(
        self,
        seed: Optional[int] = None,
        options: Optional[Dict[str, Any]] = None,
    ) -> Tuple[Dict[str, np.ndarray], Dict[str, Any]]:
        """
        Resets the multi-agent environment and returns per-agent initial observations.
        """
        if getattr(self, "_needs_bridge", False):
            self._ensure_bridge_running()
            self._connect_ws()
            self._needs_bridge = False

        self._step_count = 0
        self._episode_index += 1
        self.reward_components = []
        if self.reward_shaper is not None:
            self.reward_shaper.reset()
        self._pending_pass = None

        # Self-play / opponent-pool selection: pick an opponent for this episode.
        if self.opponent_pool is not None:
            self.current_opponent = self.opponent_pool.sample()
            self.opponent_pool.apply(self.current_opponent, self)

        target_scenario = self.scenario
        if options and "scenario" in options:
            target_scenario = options["scenario"]

        # Batched mode: reset all sub-envs via the bridge pool and expose the
        # first sub-env through the standard PettingZoo reset() contract.
        if self.batch_size > 1:
            seeds = [int(seed) + i if seed is not None else None for i in range(self.batch_size)]
            batch_results = self.reset_batch(seeds)
            first_obs, first_info = batch_results[0]
            self.possible_agents = list(first_obs.keys())
            self.agents = list(self.possible_agents)
            return first_obs, first_info

        payload: Dict[str, Any] = {
            "type": "reset",
            "scenario": target_scenario,
        }
        if seed is not None:
            payload["seed"] = int(seed)

        if self.ws_client is None:
            self._connect_ws()

        try:
            self.ws_client.send(json.dumps(payload))
            data = self._recv_reset_response()
        except Exception:
            self._connect_ws()
            self.ws_client.send(json.dumps(payload))
            data = self._recv_reset_response()

        info_data = data.get("info", {})
        controllable_ids = info_data.get("controllableAgentIds", [])
        if not controllable_ids:
            # Fallback if single agent
            controlled_id = info_data.get("controlledPlayerId", "left_1")
            controllable_ids = [controlled_id]

        self.possible_agents = list(controllable_ids)
        self.agents = list(self.possible_agents)

        # Observations list from reset response
        raw_obs_list = data.get("observations", [])
        if not raw_obs_list and "observation" in data:
            raw_obs_list = [data["observation"]]

        observations: Dict[str, np.ndarray] = {}
        action_masks: Dict[str, np.ndarray] = {}
        for idx, agent in enumerate(self.agents):
            if idx < len(raw_obs_list):
                obs = np.array(raw_obs_list[idx], dtype=np.float32)
            else:
                obs = np.zeros(OBSERVATION_DIM, dtype=np.float32)
            observations[agent] = obs
            action_masks[agent] = np.ones(19, dtype=np.int8)

        infos: Dict[str, Any] = {agent: dict(info_data) for agent in self.agents}
        for agent in self.agents:
            infos[agent]["action_mask"] = action_masks[agent]
        return {agent: {"observation": observations[agent], "action_mask": action_masks[agent]} for agent in self.agents}, infos

    @staticmethod
    def _resolve_pending_pass_state(
        pending_pass: Optional[Dict[str, Any]],
        ball_owner_agent_idx: int,
        current_ev_type: Optional[str],
        agents: List[str],
    ) -> Tuple[List[Dict[str, Any]], Optional[Dict[str, Any]]]:
        """
        Stateless pending-pass resolution. Returns (resolution_events, new_pending_pass).
        Used by both the single-env step() and the batched step_batch() path.
        """
        events: List[Dict[str, Any]] = []

        # A new pass attempt while one is pending: clear the stale pending
        # pass; the engine's explicit pass_completed / pass_intercepted events
        # (Phase 11) are the authoritative source of truth.
        if current_ev_type == "pass" and pending_pass is not None:
            pending_pass = None

        if pending_pass is not None:
            pending_pass["age"] += 1
            resolved_type: Optional[str] = None
            if 0 <= ball_owner_agent_idx < len(agents):
                owner_id = agents[ball_owner_agent_idx]
                if owner_id != pending_pass["agent_id"]:
                    resolved_type = (
                        "PASS_FAILED" if owner_id.startswith("right_") else "PASS_COMPLETED"
                    )
            elif current_ev_type in ("interception", "tackle", "foul", "out_of_bounds", "offside", "pass_intercepted"):
                resolved_type = "PASS_FAILED"
            if resolved_type is None and pending_pass["age"] > 60:
                resolved_type = "PASS_FAILED"
            if resolved_type is not None:
                events.append(
                    {
                        "type": resolved_type,
                        "team": "left",
                        "agent_id": pending_pass["agent_id"],
                    }
                )
                pending_pass = None

        if current_ev_type == "pass" and pending_pass is None:
            passer = (
                agents[ball_owner_agent_idx]
                if 0 <= ball_owner_agent_idx < len(agents)
                else None
            )
            pending_pass = {"agent_id": passer, "age": 0}

        return events, pending_pass

    def _resolve_pending_pass(
        self,
        ball_owner_agent_idx: int,
        current_ev_type: Optional[str],
    ) -> List[Dict[str, Any]]:
        """Legacy single-env wrapper around _resolve_pending_pass_state."""
        events, self._pending_pass = GMNMultiAgentEnv._resolve_pending_pass_state(
            self._pending_pass, ball_owner_agent_idx, current_ev_type, self.agents
        )
        return events

    @staticmethod
    def _build_shaper_events(
        event_code: int,
        score_l: int,
        score_r: int,
        agents: List[str],
        ball_owner_agent_idx: int,
    ) -> List[Dict[str, Any]]:
        """Map a binary frame event_code to shaper-consumable step_events."""
        step_events: List[Dict[str, Any]] = []
        if 0 < event_code < len(EVENT_CODE_MAP):
            ev_type = EVENT_CODE_MAP[event_code]
            if ev_type:
                shaper_type = None
                shaper_team = "left"
                if ev_type == "pass":
                    shaper_type = None
                elif ev_type == "shot":
                    shaper_type = "SHOT_TAKEN"
                elif ev_type == "shot_saved":
                    shaper_type = "SHOT_SAVED"
                elif ev_type == "shot_missed":
                    shaper_type = "SHOT_MISSED"
                elif ev_type == "goal":
                    shaper_type = "GOAL_SCORED"
                    shaper_team = "left" if score_l > 0 else "right"
                elif ev_type in ("interception", "tackle", "foul"):
                    shaper_type = "TURNOVER_CONCEDED"
                    shaper_team = "right"
                elif ev_type == "pass_completed":
                    shaper_type = "PASS_COMPLETED"
                    shaper_team = "left"
                elif ev_type == "pass_intercepted":
                    shaper_type = "PASS_INTERCEPTED"
                    shaper_team = "right"

                if shaper_type is not None:
                    event_dict: Dict[str, Any] = {"type": shaper_type, "team": shaper_team}
                    if 0 <= ball_owner_agent_idx < len(agents):
                        event_dict["agent_id"] = agents[ball_owner_agent_idx]
                    step_events.append(event_dict)
        return step_events

    @staticmethod
    def _apply_shaping_for_env(
        env_state: Dict[str, Any],
        shared_reward: float,
        shared_term: bool,
        shared_trunc: bool,
        event_code: int,
        ball_owner_agent_idx: int,
        score_l: int,
        score_r: int,
        actions: Dict[str, int],
    ) -> Dict[str, float]:
        """M5: Apply cooperative reward shaping for one sub-environment."""
        shaper = env_state.get("reward_shaper")
        if shaper is None:
            return {}

        current_ev_type = EVENT_CODE_MAP[event_code] if 0 < event_code < len(EVENT_CODE_MAP) else None
        agents = env_state["agents"]

        # Build step_events from the frame's event_code.
        step_events = GMNMultiAgentEnv._build_shaper_events(event_code, score_l, score_r, agents, ball_owner_agent_idx)

        # Resolve pending pass for this sub-env.
        resolution_events, env_state["pending_pass"] = GMNMultiAgentEnv._resolve_pending_pass_state(
            env_state.get("pending_pass"), ball_owner_agent_idx, current_ev_type, agents
        )
        step_events = resolution_events + step_events

        # Store actions for shot-attribution fallback.
        env_state["last_actions"] = actions

        current_ball_owner = None
        if 0 <= ball_owner_agent_idx < len(agents):
            agent_id = agents[ball_owner_agent_idx]
            team = "left" if not agent_id.startswith("right_") else "right"
            current_ball_owner = {"agent_id": agent_id, "team": team}

        try:
            return shaper.compute_shaped_rewards(
                base_rewards={a: shared_reward for a in agents},
                step_events=step_events,
                info_ground_truth={"current_ball_owner": current_ball_owner},
                active_agents=list(agents),
                actions=actions,
            )
        except Exception:
            return {}

    def step(
        self,
        actions: Dict[str, int],
    ) -> Tuple[
        Dict[str, np.ndarray],
        Dict[str, float],
        Dict[str, bool],
        Dict[str, bool],
        Dict[str, Any],
    ]:
        """
        Executes a multi-agent joint action step.
        actions: mapping from agent ID to discrete action (0..18).
        """
        # Batched mode: delegate to step_batch for all sub-environments and
        # return only the first sub-env's result through the standard contract.
        if self.batch_size > 1:
            batch_results = self.step_batch([actions])
            if not batch_results:
                return {}, {}, {}, {}, {}
            return batch_results[0]

        if not self.agents:
            return {}, {}, {}, {}, {}

        self._step_count += 1
        num_agents = len(self.agents)

        # Pack actions strictly in self.agents (controllableAgentIds) order
        action_bytes = bytearray(num_agents)
        for i, agent in enumerate(self.agents):
            act = int(actions.get(agent, 0))
            if not (0 <= act < ACTION_SPACE_SIZE):
                raise ValueError(
                    f"[GMN-PettingZoo] Invalid action {act} for agent {agent}. Must be in [0, {ACTION_SPACE_SIZE - 1}]."
                )
            action_bytes[i] = act

        if self.ws_client is None:
            self._connect_ws()

        try:
            self.ws_client.send(bytes(action_bytes))
            data, episode_stats, defender_reward, reward_components = self._recv_step_response(num_agents)
        except Exception as e:
            # Log bridge errors for forensic debugging
            if getattr(self, "_forensic_debug", False):
                import sys as _sys
                print(
                    f"[FORENSIC_BRIDGE_ERROR]\n"
                    f"scenario={self.scenario}\n"
                    f"episode={getattr(self, '_episode_index', -1)}\n"
                    f"global_step={self._step_count}\n"
                    f"error_type={type(e).__name__}\n"
                    f"error_message={str(e)}\n"
                    f"bridge_error_count={getattr(self, '_bridge_error_count', 0)}\n"
                    f"[END_FORENSIC_BRIDGE_ERROR]",
                    flush=True,
                    file=_sys.stderr,
                )
            self._connect_ws()
            self.ws_client.send(bytes(action_bytes))
            data, episode_stats, defender_reward, reward_components = self._recv_step_response(num_agents)

        if isinstance(data, str):
            raise RuntimeError(f"[GMN-PettingZoo] Bridge sent text error: {data}")
        if not isinstance(data, (bytes, bytearray)):
            raise RuntimeError(f"[GMN-PettingZoo] Expected binary WebSocket frame, got {type(data)}")

        obs_bytes = OBSERVATION_DIM * 4
        is_rondo = self.scenario == "academy_rondo_4v1"
        header_size = 22 if is_rondo else 18
        mask_bytes = 19
        expected_len = header_size + obs_bytes * num_agents + mask_bytes * num_agents
        if len(data) != expected_len:
            raise RuntimeError(
                f"[GMN-PettingZoo Frame Length Error] Expected {expected_len} bytes "
                f"({header_size}B header + {obs_bytes}B * {num_agents} agents + {mask_bytes}B * {num_agents} masks), but received {len(data)} bytes."
            )

        # Unpack header
        reward, term, trunc, score_l, score_r, cp_reward, dist_goal, event_code, ball_owner_agent_idx = struct.unpack_from(
            "<f??BBffBB", data, 0
        )

        # Bridge error-frame sentinel (P0 #5): surface loudly instead of silently
        # accumulating a -999 penalty into episode reward.
        if float(reward) <= -998.0 and bool(term):
            self._bridge_error_count += 1
            raise RuntimeError(
                "[GMN-PettingZoo Bridge Error] Bridge returned an error frame "
                "(reward <= -998.0, terminated=true). This indicates an internal "
                "bridge error (e.g., invalid action, engine exception, or WebSocket "
                "failure). Check the bridge server logs for the root cause."
            )

        # For rondo scenarios, the bridge sends a split reward: attacker reward in the
        # standard reward field, and a separate defenderReward at offset 18
        # (observations start at 22).
        if is_rondo:
            defender_reward = struct.unpack_from("<f", data, 18)[0]

        shared_reward = float(reward)
        shared_term = bool(term)
        shared_trunc = bool(trunc)

        # Step 2/3 provenance: capture raw binary-frame values on every tick.
        # On terminal ticks these are the exact values that entered the pipeline.
        self._last_frame_reward = float(reward)
        self._last_frame_event_code = int(event_code)
        self._last_frame_score = {"left": int(score_l), "right": int(score_r)}
        self._last_shared_reward = shared_reward

        shared_info: Dict[str, Any] = {
            "score": {"left": int(score_l), "right": int(score_r)},
            "checkpointReward": float(cp_reward),
            "ballDistanceToGoal": float(dist_goal),
            "eventCode": int(event_code),
            "frame_length": len(data),
            "step": self._step_count,
        }
        if 0 < event_code < len(EVENT_CODE_MAP):
            ev_type = EVENT_CODE_MAP[event_code]
            if ev_type:
                shared_info["event"] = {"type": ev_type}

        # Attach ground-truth engine stats if the bridge sent them on episode end.
        # Include both termination (goal/scenario_complete) and truncation (clock expiry)
        # so pass/shot accuracy is computed for all episode endings, not just goals.
        if episode_stats and (shared_term or shared_trunc):
            shared_info["ground_truth"] = {
                "possession_left_pct": episode_stats.get("possession_left_pct"),
                "completed_passes_left": episode_stats.get("completed_passes_left"),
                "attempted_passes_left": episode_stats.get("attempted_passes_left"),
                "shots_on_target_left": episode_stats.get("shots_on_target_left"),
                "total_shots_left": episode_stats.get("total_shots_left"),
                "pass_accuracy": (
                    episode_stats.get("completed_passes_left", 0) / episode_stats.get("attempted_passes_left", 1)
                    if episode_stats.get("attempted_passes_left", 0) > 0
                    else 0.0
                ),
                "shot_accuracy": (
                    episode_stats.get("shots_on_target_left", 0) / episode_stats.get("total_shots_left", 1)
                    if episode_stats.get("total_shots_left", 0) > 0
                    else 0.0
                ),
                "current_ball_owner": episode_stats.get("current_ball_owner"),
            }

        # Standardized evaluator metrics: expose episode lengths on termination.
        if shared_term or shared_trunc:
            shared_info["episode_length_steps"] = self._step_count
            shared_info["episode_physics_ticks"] = self._step_count

        # Parse action masks (19 bytes per agent, after observations)
        mask_offset = header_size + num_agents * obs_bytes
        action_masks: Dict[str, np.ndarray] = {}
        for i, agent in enumerate(self.agents):
            agent_mask_offset = mask_offset + i * 19
            mask = np.frombuffer(data, dtype="<u1", count=19, offset=agent_mask_offset).copy().astype(np.int8)
            action_masks[agent] = mask

        # Build per-step step_events for reward shaping from the single event_code
        step_events: List[Dict[str, Any]] = []
        if 0 < event_code < len(EVENT_CODE_MAP):
            ev_type = EVENT_CODE_MAP[event_code]
            if ev_type:
                # Map engine event types to shaper-consumable event types.
                # Engine emits: pass, shot, shot_saved, shot_missed, goal,
                # interception, tackle, foul, kickoff, out_of_bounds,
                # scenario_complete, scenario_failed, offside
                # Shaper expects: PASS_COMPLETED, PASS_FAILED, TURNOVER_CONCEDED,
                # SHOT_TAKEN, GOAL_SCORED
                shaper_type = None
                shaper_team = "left"
                if ev_type == "pass":
                    # Engine emits "pass" at initiation. Do NOT credit a completed
                    # pass here; _resolve_pending_pass() finalizes it when a
                    # teammate gains possession (or it fails / times out).
                    shaper_type = None
                elif ev_type == "shot":
                    shaper_type = "SHOT_TAKEN"
                elif ev_type == "shot_saved":
                    shaper_type = "SHOT_SAVED"
                elif ev_type == "shot_missed":
                    shaper_type = "SHOT_MISSED"
                elif ev_type == "goal":
                    shaper_type = "GOAL_SCORED"
                    shaper_team = "left" if score_l > 0 else "right"
                elif ev_type in ("interception", "tackle", "foul"):
                    shaper_type = "TURNOVER_CONCEDED"
                    shaper_team = "right"
                elif ev_type == "pass_completed":
                    shaper_type = "PASS_COMPLETED"
                    shaper_team = "left"
                elif ev_type == "pass_intercepted":
                    shaper_type = "PASS_INTERCEPTED"
                    shaper_team = "right"

                if shaper_type is not None:
                    event_dict: Dict[str, Any] = {"type": shaper_type, "team": shaper_team}
                    # Attach agent_id if ball owner is a controllable agent
                    if 0 <= ball_owner_agent_idx < len(self.agents):
                        event_dict["agent_id"] = self.agents[ball_owner_agent_idx]
                    step_events.append(event_dict)

        # Resolve the pending pass (state machine over possession) and prepend the
        # resolution so a completed pass is credited before a same-step SHOT_TAKEN
        # (keeps chain-aware shaping ordering correct).
        if self.enable_reward_shaping and self.reward_shaper is not None:
            current_ev_type = (
                EVENT_CODE_MAP[event_code] if 0 < event_code < len(EVENT_CODE_MAP) else None
            )
            step_events = (
                self._resolve_pending_pass(ball_owner_agent_idx, current_ev_type) + step_events
            )

        observations: Dict[str, np.ndarray] = {}
        rewards: Dict[str, float] = {}
        terminations: Dict[str, bool] = {}
        truncations: Dict[str, bool] = {}
        infos: Dict[str, Any] = {}

        for i, agent in enumerate(self.agents):
            offset = header_size + i * obs_bytes
            obs = np.frombuffer(data, dtype="<f4", count=OBSERVATION_DIM, offset=offset).copy()
            # Rondo: assign team-specific rewards; non-rondo keeps the shared broadcast.
            if is_rondo:
                rewards[agent] = defender_reward if agent.startswith("right_") else shared_reward
            else:
                rewards[agent] = shared_reward
            terminations[agent] = shared_term
            truncations[agent] = shared_trunc
            infos[agent] = dict(shared_info)
            infos[agent]["action_mask"] = action_masks[agent]
            observations[agent] = {
                "observation": obs,
                "action_mask": action_masks[agent],
            }
            if step_events:
                infos[agent]["step_events"] = step_events

        # Collect debug reward components if enabled
        if self.debug_rewards and reward_components is not None:
            self.reward_components.append({
                "step": self._step_count,
                "components": reward_components,
                "shared_reward": shared_reward,
                "event_code": int(event_code),
            })

        # Apply cooperative reward shaping if enabled.
        # NOTE: reward shaper must run on terminal steps too, because its internal
        # cumulative counters (goals, passes, turnovers) are side effects of
        # compute_shaped_rewards(). Skipping it on terminal steps makes the
        # live-training event counters blind to any goal scored on the final tick.
        if self.enable_reward_shaping and self.reward_shaper is not None:
            try:
                # Derive current ball owner from binary frame ballOwnerAgentId
                current_ball_owner = None
                if 0 <= ball_owner_agent_idx < len(self.agents):
                    agent_id = self.agents[ball_owner_agent_idx]
                    team = "left"
                    if agent_id.startswith("right_"):
                        team = "right"
                    current_ball_owner = {"agent_id": agent_id, "team": team}

                shaped_rewards = self.reward_shaper.compute_shaped_rewards(
                    base_rewards=rewards,
                    step_events=step_events,
                    info_ground_truth={"current_ball_owner": current_ball_owner},
                    active_agents=list(self.agents),
                    actions=actions,
                )
                # M2: Always apply shaped rewards, including on terminal steps.
                # The engine's raw reward (e.g. +2.00 goal signal) is already in
                # `rewards[agent]`; the shaper adds cooperative bonuses on top.
                # Skipping on terminal steps caused goal bonuses and assisted-goal
                # bonuses to be silently dropped.
                for agent in self.agents:
                    if agent in shaped_rewards:
                        rewards[agent] = shaped_rewards[agent]
            except Exception as e:
                logger.debug(f"Reward shaping skipped due to error: {e}")

        # Phase 2: FORENSIC_ENV_TERMINAL capture
        if getattr(self, "_forensic_debug", False) and (shared_term or shared_trunc):
            shaping_applied = (
                self.enable_reward_shaping
                and self.reward_shaper is not None
                and not shared_term
                and not shared_trunc
            )
            print(
                f"[FORENSIC_ENV_TERMINAL]\n"
                f"scenario={self.scenario}\n"
                f"episode={self._episode_index}\n"
                f"global_step={self._step_count}\n"
                f"\n"
                f"parser_reward={float(reward)}\n"
                f"env_reward={shared_reward}\n"
                f"\n"
                f"terminated_any={shared_term}\n"
                f"truncated_any={shared_trunc}\n"
                f"\n"
                f"agents={list(self.agents)}\n"
                f"agent_rewards={rewards}\n"
                f"\n"
                f"shared_reward={shared_reward}\n"
                f"\n"
                f"reward_shaper_enabled={self.enable_reward_shaping}\n"
                f"reward_shaper_skipped={not shaping_applied}\n"
                f"\n"
                f"score_left={score_l}\n"
                f"score_right={score_r}\n"
                f"event_code={event_code}\n"
                f"ball_owner_agent_idx={ball_owner_agent_idx}\n"
                f"[END_FORENSIC_ENV_TERMINAL]",
                flush=True,
            )

        if shared_term or shared_trunc:
            self.agents = []

        return observations, rewards, terminations, truncations, infos

    def render(self):
        """Render mode placeholder."""
        if self.render_mode == "human":
            print(f"[GMNMultiAgentEnv] Step: {self._step_count} | Agents: {self.possible_agents}")

    def close(self):
        """Cleans up WebSocket connection and bridge subprocess."""
        if self.ws_client is not None:
            try:
                self.ws_client.send(json.dumps({"type": "close"}))
                self.ws_client.close()
            except Exception:
                pass
            self.ws_client = None

        if self.bridge_process is not None:
            try:
                self.bridge_process.terminate()
                self.bridge_process.wait(timeout=2.0)
            except Exception:
                pass
            self.bridge_process = None

    def __getstate__(self):
        """Allows pickling by excluding unpicklable socket/process references."""
        state = self.__dict__.copy()
        state["ws_client"] = None
        state["bridge_process"] = None
        return state

    def __setstate__(self, state):
        """Restores state from pickle and marks client/process for lazy re-initialization."""
        self.__dict__.update(state)
        self.bridge_process = None
        self.ws_client = None
        self._needs_bridge = True
