def _npx_cmd():
    return ["npx.cmd"] if sys.platform == "win32" else ["npx"]


# --- P0.5d bridge startup budget ---------------------------------------------
# Unchanged from the pre-P0.5d loop: one spawn attempt followed by
# 24 re-checks. Sleeps total 1.0 + 24 * 0.4 = 10.6 s. The budget is NOT
# changed by P0.5d; only the failure behaviour when it is exhausted.
BRIDGE_STARTUP_ATTEMPTS = 25
BRIDGE_STARTUP_SLEEP_AFTER_SPAWN = 1.0
BRIDGE_STARTUP_SLEEP_BETWEEN = 0.4

# Marker that identifies a process as one of our bridge processes. Used to
# scope port reaping so an unrelated listener is never killed.
BRIDGE_PROCESS_MARKER = "bridge_server.ts"


def _parse_netstat_listening_pids(lines, port: int) -> set:
    """Extract Windows TCP-LISTENING pids for one local port.

    Deliberately strict: requires the row to be TCP (so UDP bind rows for the
    same port number are ignored) and to be in the LISTENING state.
    """
    port_text = str(port)
    pids = set()
    for line in lines:
        parts = line.split()
        if (
            len(parts) >= 5
            and parts[0].strip().upper() == "TCP"
            and parts[-2].strip().upper() == "LISTENING"
            and parts[1].rsplit(":", 1)[-1] == port_text
        ):
            pids.add(parts[-1])
    return pids


def _process_command_line(pid) -> str:
    """Best-effort command line lookup for a pid (empty string if unknown)."""
    if sys.platform != "win32":
        return ""
    try:
        out = subprocess.check_output(
            [
                "powershell",
                "-NoProfile",
                "-NonInteractive",
                "-Command",
                f"(Get-CimInstance Win32_Process -Filter \"ProcessId={pid}\").CommandLine",
            ],
            text=True,
            stderr=subprocess.DEVNULL,
            timeout=8.0,
        )
        return (out or "").strip()
    except Exception:
        return ""


